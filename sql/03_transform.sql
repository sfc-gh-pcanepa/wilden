-- 03_transform.sql
-- Willdan Group demo -- TRANSFORM layer (UDF + dynamic tables).
-- ALL DATA IS SYNTHETIC (simulated Deltek CostPoint extracts). No real Willdan data.
USE ROLE WILLDAN_DEMO_ADMIN;
USE WAREHOUSE WILLDAN_WH;
USE DATABASE WILLDAN_DEMO;
CREATE SCHEMA IF NOT EXISTS CURATED;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

-- 1. Text cleaning UDF (synthetic text contains commas, quotes, dashes, tabs, newlines)
CREATE OR REPLACE FUNCTION CURATED.CLEAN_TEXT(S STRING)
RETURNS STRING
COMMENT = 'Synthetic demo: normalize CostPoint free text for comma-delimited feeds'
AS
$$
  NULLIF(TRIM(REGEXP_REPLACE(
    TRANSLATE(S, '–—",' || CHR(9) || CHR(13) || CHR(10), '--     '),
    '\\s+', ' ')), '')
$$;

-- 2. Dynamic tables
CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_ORG
  TARGET_LAG = DOWNSTREAM WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: org hierarchy with company (business unit)'
AS
SELECT o.ORG_ID,
       CURATED.CLEAN_TEXT(o.ORG_NAME) AS ORG_NAME,
       NULLIF(TRIM(o.PARENT_ORG_ID),'') AS PARENT_ORG_ID,
       TRY_TO_NUMBER(o.LVL_NO) AS LVL_NO,
       TRIM(o.COMPANY_CD) AS BUSINESS_UNIT,
       CURATED.CLEAN_TEXT(c.ORG_NAME) AS BUSINESS_UNIT_NAME
FROM RAW.ORG_RAW o
LEFT JOIN RAW.ORG_RAW c ON c.ORG_ID = SPLIT_PART(o.ORG_ID, '.', 1)
QUALIFY ROW_NUMBER() OVER (PARTITION BY o.ORG_ID ORDER BY o._LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_EMPLOYEE
  TARGET_LAG = DOWNSTREAM WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: employee dimension'
AS
SELECT TRIM(e.EMPL_ID) AS EMPLOYEE_ID,
       CURATED.CLEAN_TEXT(e.FIRST_NAME || ' ' || e.LAST_NAME) AS EMPLOYEE_NAME,
       CURATED.CLEAN_TEXT(e.TITLE) AS TITLE,
       TRY_TO_NUMBER(e.BILL_RATE, 10, 2) AS BILL_RATE,
       TRIM(e.HOME_ORG_ID) AS HOME_ORG_ID,
       o.ORG_NAME AS HOME_ORG_NAME,
       o.BUSINESS_UNIT,
       TRY_TO_DATE(e.HIRE_DT) AS HIRE_DATE,
       TRY_TO_DATE(NULLIF(TRIM(e.TERM_DT),'')) AS TERM_DATE,
       TRIM(e.STATUS) AS STATUS,
       TRIM(e.STATUS) = 'A' AS IS_ACTIVE
FROM RAW.EMPL_RAW e
LEFT JOIN CURATED.DIM_ORG o ON o.ORG_ID = TRIM(e.HOME_ORG_ID)
QUALIFY ROW_NUMBER() OVER (PARTITION BY e.EMPL_ID ORDER BY e._LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE CURATED.DIM_PROJECT
  TARGET_LAG = DOWNSTREAM WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: leaf project (WBS level 2) dimension'
AS
WITH p AS (
  SELECT * FROM RAW.PROJ_RAW
  QUALIFY ROW_NUMBER() OVER (PARTITION BY PROJ_ID ORDER BY _LOADED_AT DESC) = 1),
c AS (
  SELECT * FROM RAW.CUST_RAW
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CUST_ID ORDER BY _LOADED_AT DESC) = 1)
SELECT TRIM(l.PROJ_ID) AS PROJECT_ID,
       CURATED.CLEAN_TEXT(l.PROJ_NAME) AS PROJECT_NAME,
       TRIM(l.PARENT_PROJ_ID) AS PROGRAM_ID,
       CURATED.CLEAN_TEXT(pg.PROJ_NAME) AS PROGRAM_NAME,
       TRIM(COALESCE(NULLIF(TRIM(l.CUST_ID),''), pg.CUST_ID)) AS CUSTOMER_ID,
       CURATED.CLEAN_TEXT(c.CUST_NAME) AS CUSTOMER_NAME,
       TRIM(l.ORG_ID) AS ORG_ID,
       o.ORG_NAME,
       o.BUSINESS_UNIT,
       TRIM(l.PM_EMPL_ID) AS PM_EMPLOYEE_ID,
       e.EMPLOYEE_NAME AS PM_NAME,
       CURATED.CLEAN_TEXT(l.CONTRACT_TYPE) AS CONTRACT_TYPE,
       TRY_TO_NUMBER(l.CONTRACT_VALUE, 14, 2) AS CONTRACT_VALUE,
       TRY_TO_DATE(l.START_DT) AS START_DATE,
       TRY_TO_DATE(l.END_DT) AS END_DATE
FROM p l
LEFT JOIN p pg ON pg.PROJ_ID = l.PARENT_PROJ_ID
LEFT JOIN c ON c.CUST_ID = COALESCE(NULLIF(TRIM(l.CUST_ID),''), pg.CUST_ID)
LEFT JOIN CURATED.DIM_ORG o ON o.ORG_ID = TRIM(l.ORG_ID)
LEFT JOIN CURATED.DIM_EMPLOYEE e ON e.EMPLOYEE_ID = TRIM(l.PM_EMPL_ID)
WHERE TRY_TO_NUMBER(l.LVL_NO) = 2;

CREATE OR REPLACE DYNAMIC TABLE CURATED.FACT_LABOR
  TARGET_LAG = '15 minutes' WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: typed, cleaned, deduped CostPoint labor lines'
AS
SELECT TRY_TO_NUMBER(l.LAB_ID) AS LAB_ID,
       TRY_TO_DATE(l.TS_DT) AS WORK_DATE,
       TO_CHAR(TRY_TO_DATE(l.TS_DT), 'YYYY-MM') AS PERIOD,
       TRIM(l.FY_CD) AS FY,
       TRY_TO_NUMBER(l.PD_NO) AS PD,
       TRIM(l.EMPL_ID) AS EMPLOYEE_ID,
       TRIM(l.PROJ_ID) AS PROJECT_ID,
       p.PROGRAM_ID,
       TRIM(l.ORG_ID) AS ORG_ID,
       o.BUSINESS_UNIT,
       TRIM(l.ACCT_ID) AS GL_ACCOUNT,
       TRIM(l.ACCT_ID) = '5100' AS IS_BILLABLE,
       TRY_TO_NUMBER(l.HOURS, 10, 2) AS HOURS,
       TRY_TO_NUMBER(l.BILL_RATE, 10, 2) AS BILL_RATE,
       TRY_TO_NUMBER(l.LAB_AMT, 14, 2) AS LABOR_COST,
       DECODE(TRIM(l.STATUS), 'A', 'Approved', 'P', 'Pending', TRIM(l.STATUS)) AS STATUS,
       CURATED.CLEAN_TEXT(l.NOTES) AS NOTES,
       l._SOURCE_FILE AS SOURCE_FILE,
       l._LOADED_AT AS LOADED_AT
FROM RAW.LAB_HS_RAW l
LEFT JOIN CURATED.DIM_PROJECT p ON p.PROJECT_ID = TRIM(l.PROJ_ID)
LEFT JOIN CURATED.DIM_ORG o ON o.ORG_ID = TRIM(l.ORG_ID)
QUALIFY ROW_NUMBER() OVER (PARTITION BY l.LAB_ID ORDER BY l._LOADED_AT DESC) = 1;

CREATE OR REPLACE DYNAMIC TABLE ANALYTICS.PROJECT_BURN
  TARGET_LAG = '15 minutes' WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: project burn vs schedule as of fixed date 2026-11-05'
AS
WITH lab AS (
  SELECT PROJECT_ID,
         SUM(LABOR_COST) AS LABOR_TO_DATE,
         SUM(IFF(WORK_DATE > DATEADD(day, -30, '2026-11-05'::DATE), LABOR_COST, 0)) AS LABOR_LAST_30D,
         SUM(IFF(STATUS = 'Pending', LABOR_COST, 0)) AS PENDING_LABOR,
         SUM(HOURS) AS HOURS_TO_DATE
  FROM CURATED.FACT_LABOR GROUP BY PROJECT_ID),
b AS (
  SELECT p.PROJECT_ID, p.PROJECT_NAME, p.PROGRAM_NAME, p.CUSTOMER_NAME, p.BUSINESS_UNIT,
         p.PM_NAME, p.CONTRACT_TYPE, p.CONTRACT_VALUE, p.START_DATE, p.END_DATE,
         COALESCE(l.LABOR_TO_DATE, 0) AS LABOR_TO_DATE,
         COALESCE(l.LABOR_LAST_30D, 0) AS LABOR_LAST_30D,
         COALESCE(l.PENDING_LABOR, 0) AS PENDING_LABOR,
         COALESCE(l.HOURS_TO_DATE, 0) AS HOURS_TO_DATE,
         p.CONTRACT_VALUE - COALESCE(l.LABOR_TO_DATE, 0) AS BUDGET_REMAINING,
         ROUND(DIV0NULL(COALESCE(l.LABOR_TO_DATE, 0), p.CONTRACT_VALUE) * 100, 1) AS BURN_PCT,
         ROUND(LEAST(100, GREATEST(0, DIV0NULL(DATEDIFF(day, p.START_DATE, '2026-11-05'::DATE),
               DATEDIFF(day, p.START_DATE, p.END_DATE)) * 100)), 1) AS SCHEDULE_PCT
  FROM CURATED.DIM_PROJECT p LEFT JOIN lab l ON l.PROJECT_ID = p.PROJECT_ID)
SELECT b.*,
       BURN_PCT - SCHEDULE_PCT AS BURN_VS_SCHEDULE_GAP,
       (BURN_PCT > SCHEDULE_PCT + 5 OR BURN_PCT > 100) AS AT_RISK,
       '2026-11-05'::DATE AS AS_OF_DATE
FROM b;

