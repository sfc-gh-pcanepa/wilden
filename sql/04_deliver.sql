-- Willdan Group demo -- DELIVER layer (feed views, outbound stage, export proc, tasks).
-- ALL DATA IS SYNTHETIC (simulated Deltek CostPoint extracts). No real Willdan data.
USE ROLE WILLDAN_DEMO_ADMIN;
USE WAREHOUSE WILLDAN_WH;
USE DATABASE WILLDAN_DEMO;

-- DELIVER (synthetic feeds)
CREATE OR REPLACE VIEW CURATED.FEED_ADAPTIVE_LABOR
  COMMENT = 'Synthetic demo: monthly approved labor feed for Adaptive Planning'
AS
SELECT BUSINESS_UNIT AS ENTITY, ORG_ID, PROJECT_ID, GL_ACCOUNT, PERIOD,
       SUM(HOURS) AS HOURS, SUM(LABOR_COST) AS LABOR_COST
FROM CURATED.FACT_LABOR
WHERE STATUS = 'Approved'
GROUP BY ALL;

CREATE OR REPLACE VIEW CURATED.FEED_PM_LABOR_DETAIL
  COMMENT = 'Synthetic demo: line-level labor detail feed for project managers'
AS
SELECT f.PERIOD, f.PROJECT_ID, p.PROJECT_NAME, e.EMPLOYEE_NAME, f.WORK_DATE,
       f.HOURS, f.BILL_RATE, f.LABOR_COST, f.IS_BILLABLE, f.STATUS, f.NOTES
FROM CURATED.FACT_LABOR f
LEFT JOIN CURATED.DIM_PROJECT p ON p.PROJECT_ID = f.PROJECT_ID
LEFT JOIN CURATED.DIM_EMPLOYEE e ON e.EMPLOYEE_ID = f.EMPLOYEE_ID;

CREATE STAGE IF NOT EXISTS CURATED.OUTBOUND
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Synthetic demo: outbound feed files';

CREATE TABLE IF NOT EXISTS CURATED.EXPORT_LOG (
  RUN_ID STRING DEFAULT UUID_STRING(), FEED STRING, PERIOD STRING, PATH STRING,
  ROWS_EXPORTED NUMBER, STATUS STRING, MESSAGE STRING,
  STARTED_AT TIMESTAMP_LTZ, FINISHED_AT TIMESTAMP_LTZ)
  COMMENT = 'Synthetic demo: feed export audit log';

CREATE OR REPLACE PROCEDURE CURATED.SP_EXPORT_FEED(FEED STRING, PERIOD STRING)
RETURNS STRING
LANGUAGE SQL
COMMENT = 'Synthetic demo: export an allowlisted feed for one period to @OUTBOUND'
EXECUTE AS OWNER
AS
$$
DECLARE
  v_feed STRING DEFAULT UPPER(TRIM(:FEED));
  v_period STRING DEFAULT COALESCE(:PERIOD, TO_CHAR(DATEADD(month, -1, CURRENT_DATE()), 'YYYY-MM'));
  v_view STRING;
  v_path STRING;
  v_rows NUMBER DEFAULT 0;
  v_started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  v_msg STRING;
  v_sql STRING;
BEGIN
  v_view := CASE :v_feed
              WHEN 'ADAPTIVE_LABOR'  THEN 'WILLDAN_DEMO.CURATED.FEED_ADAPTIVE_LABOR'
              WHEN 'PM_LABOR_DETAIL' THEN 'WILLDAN_DEMO.CURATED.FEED_PM_LABOR_DETAIL'
            END;
  IF (:v_view IS NULL) THEN
    v_msg := 'Unknown feed (not in allowlist)';
    INSERT INTO WILLDAN_DEMO.CURATED.EXPORT_LOG (FEED, PERIOD, STATUS, MESSAGE, STARTED_AT, FINISHED_AT)
      VALUES (:FEED, :PERIOD, 'FAILED', :v_msg, :v_started, CURRENT_TIMESTAMP());
    RETURN 'FAILED: ' || :v_msg;
  END IF;
  IF (NOT REGEXP_LIKE(:v_period, '^[0-9]{4}-[0-9]{2}$')) THEN
    v_msg := 'Invalid period, expected YYYY-MM';
    INSERT INTO WILLDAN_DEMO.CURATED.EXPORT_LOG (FEED, PERIOD, STATUS, MESSAGE, STARTED_AT, FINISHED_AT)
      VALUES (:v_feed, :v_period, 'FAILED', :v_msg, :v_started, CURRENT_TIMESTAMP());
    RETURN 'FAILED: ' || :v_msg;
  END IF;

  -- Only allowlisted / regex-validated values reach dynamic SQL
  v_path := LOWER(:v_feed) || '/' || :v_period || '/' || LOWER(:v_feed) || '_' || :v_period || '.csv';
  v_sql := 'SELECT COUNT(*) AS N FROM ' || :v_view || ' WHERE PERIOD = ''' || :v_period || '''';
  LET rs RESULTSET := (EXECUTE IMMEDIATE :v_sql);
  LET cur CURSOR FOR rs;
  FOR r IN cur DO
    v_rows := r.N;
  END FOR;

  IF (:v_rows = 0) THEN
    INSERT INTO WILLDAN_DEMO.CURATED.EXPORT_LOG (FEED, PERIOD, PATH, ROWS_EXPORTED, STATUS, MESSAGE, STARTED_AT, FINISHED_AT)
      VALUES (:v_feed, :v_period, NULL, 0, 'SKIPPED', 'No rows for period', :v_started, CURRENT_TIMESTAMP());
    RETURN 'SKIPPED: no rows for ' || :v_feed || ' ' || :v_period;
  END IF;

  v_sql := 'COPY INTO @WILLDAN_DEMO.CURATED.OUTBOUND/' || :v_path ||
           ' FROM (SELECT * FROM ' || :v_view || ' WHERE PERIOD = ''' || :v_period || ''')' ||
           ' FILE_FORMAT = (TYPE = CSV COMPRESSION = NONE FIELD_OPTIONALLY_ENCLOSED_BY = NONE NULL_IF = ())' ||
           ' HEADER = TRUE SINGLE = TRUE OVERWRITE = TRUE MAX_FILE_SIZE = 4900000000';
  EXECUTE IMMEDIATE :v_sql;
  SELECT "rows_unloaded" INTO :v_rows FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  INSERT INTO WILLDAN_DEMO.CURATED.EXPORT_LOG (FEED, PERIOD, PATH, ROWS_EXPORTED, STATUS, MESSAGE, STARTED_AT, FINISHED_AT)
    VALUES (:v_feed, :v_period, '@OUTBOUND/' || :v_path, :v_rows, 'SUCCESS', 'Exported', :v_started, CURRENT_TIMESTAMP());
  RETURN 'SUCCESS: ' || :v_rows || ' rows -> @OUTBOUND/' || :v_path;
EXCEPTION
  WHEN OTHER THEN
    INSERT INTO WILLDAN_DEMO.CURATED.EXPORT_LOG (FEED, PERIOD, PATH, STATUS, MESSAGE, STARTED_AT, FINISHED_AT)
      VALUES (:v_feed, :v_period, :v_path, 'FAILED', :SQLERRM, :v_started, CURRENT_TIMESTAMP());
    RETURN 'FAILED: ' || :SQLERRM;
END;
$$;

-- Tasks: root stays SUSPENDED (demo); children resumed
CREATE OR REPLACE TASK CURATED.TASK_MONTH_END_REFRESH
  WAREHOUSE = WILLDAN_WH
  SCHEDULE = 'USING CRON 0 6 2 * * America/Los_Angeles'
  COMMENT = 'Synthetic demo: month-end refresh of project burn'
AS
  ALTER DYNAMIC TABLE WILLDAN_DEMO.ANALYTICS.PROJECT_BURN REFRESH;

CREATE OR REPLACE TASK CURATED.TASK_EXPORT_ADAPTIVE
  WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: export Adaptive labor feed for prior month'
  AFTER CURATED.TASK_MONTH_END_REFRESH
AS
  CALL WILLDAN_DEMO.CURATED.SP_EXPORT_FEED('ADAPTIVE_LABOR', NULL);

CREATE OR REPLACE TASK CURATED.TASK_EXPORT_PM_DETAIL
  WAREHOUSE = WILLDAN_WH
  COMMENT = 'Synthetic demo: export PM labor detail feed for prior month'
  AFTER CURATED.TASK_MONTH_END_REFRESH
AS
  CALL WILLDAN_DEMO.CURATED.SP_EXPORT_FEED('PM_LABOR_DETAIL', NULL);

ALTER TASK CURATED.TASK_EXPORT_ADAPTIVE RESUME;
ALTER TASK CURATED.TASK_EXPORT_PM_DETAIL RESUME;
